#!/usr/bin/env node

import * as p from '@clack/prompts';
import pc from 'picocolors';
import { execFileSync, execSync, spawn } from 'child_process';
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { homedir, platform } from 'os';
import { join, resolve } from 'path';

const HOME = homedir();
const DOTFILES_DIR = resolve(join(import.meta.dirname, '..'));
const IS_MACOS = platform() === 'darwin';

// ============================================================================
// Helpers
// ============================================================================

function commandExists(cmd) {
  try {
    execSync(`command -v ${cmd}`, { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function getExistingGitConfig(key) {
  try {
    // --includes is required: without it git ignores [include] and this always
    // returns empty, since the real values live in ~/.gitconfig.local.
    return execSync(`git config --global --includes ${key}`, { stdio: 'pipe' }).toString().trim();
  } catch {
    return '';
  }
}

function getExistingGitConfigLocal() {
  const localFile = join(HOME, '.gitconfig.local');
  if (!existsSync(localFile)) return {};

  const content = readFileSync(localFile, 'utf-8');
  const result = {};
  const nameMatch = content.match(/name\s*=\s*(.+)/);
  const emailMatch = content.match(/email\s*=\s*(.+)/);
  if (nameMatch) result.name = nameMatch[1].trim();
  if (emailMatch) result.email = emailMatch[1].trim();
  return result;
}

function getComputerName() {
  if (!IS_MACOS) return '';
  try {
    return execSync('scutil --get ComputerName', { stdio: 'pipe' }).toString().trim();
  } catch {
    try {
      return execSync('hostname -s', { stdio: 'pipe' }).toString().trim();
    } catch {
      return '';
    }
  }
}

// ============================================================================
// Setup Modules
// ============================================================================

async function askWorkMachine() {
  if (process.argv.includes('--work')) return true;

  const isWork = await p.confirm({
    message: 'Is this a work machine?',
    initialValue: false,
  });

  if (p.isCancel(isWork)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  return isWork;
}

// Work machines take no identity guard, because it refuses every author except
// me@lacymorrow.com. Leaving the email empty skips git identity entirely and does not
// touch ~/.gitconfig.local, so whatever the employer provisions stays in charge.
async function setupWorkGitConfig() {
  const local = getExistingGitConfigLocal();

  const email = await p.text({
    message: 'Git email (leave empty to skip git identity)',
    placeholder: 'you@company.com',
    initialValue: local.email || getExistingGitConfig('user.email'),
    validate(value) {
      if (value && value.trim().length > 0 && !value.includes('@')) return 'Enter a valid email';
    },
  });

  if (p.isCancel(email)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  if (!email || email.trim().length === 0) {
    p.log.info(`Skipped git identity. ${pc.dim('~/.gitconfig.local')} left as it was.`);
    return null;
  }

  const name = await p.text({
    message: 'Git user name',
    placeholder: 'Your Name',
    initialValue: local.name || getExistingGitConfig('user.name'),
    validate(value) {
      if (!value || value.trim().length === 0) return 'Name is required';
    },
  });

  if (p.isCancel(name)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  writeFileSync(
    join(HOME, '.gitconfig.local'),
    `# Generated by dotfiles setup, not tracked in git\n[user]\n\tname = ${name}\n\temail = ${email.trim()}\n`
  );
  p.log.success(`Wrote ${pc.dim('~/.gitconfig.local')}`);

  return { name, email };
}

async function setupGitConfig() {
  // Read existing values: prefer .gitconfig.local, fall back to global git config
  const local = getExistingGitConfigLocal();
  const defaultName = local.name || getExistingGitConfig('user.name');
  const defaultEmail = local.email || getExistingGitConfig('user.email');

  const name = await p.text({
    message: 'Git user name',
    placeholder: 'Your Name',
    initialValue: defaultName,
    validate(value) {
      if (!value || value.trim().length === 0) return 'Name is required';
    },
  });

  if (p.isCancel(name)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  const email = await p.text({
    message: 'Git email',
    placeholder: 'you@example.com',
    initialValue: defaultEmail,
    validate(value) {
      if (!value || value.trim().length === 0) return 'Email is required';
      if (!value.includes('@')) return 'Enter a valid email';
    },
  });

  if (p.isCancel(email)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  const localFile = join(HOME, '.gitconfig.local');

  // Fleet rule 18's identity guard is wired from THIS file, and this write is a full
  // overwrite that reads back only name and email. Emitting just [user] therefore ends
  // rule 18 on the host, with no error and no log line, the next time anyone runs setup
  // for any reason. Both wirings are written whenever the guard is installed, because
  // which one git consults is decided by the git version: 2.54 and newer read the
  // config hook, anything older sees only hooksPath, and neither host has a working
  // second one. On 2.54 and newer BOTH run, so the refusal prints twice; that is
  // expected and not a bug. Nothing is emitted when the guard is absent, so a machine
  // without it is never handed a hook command that does not exist. LACA-2984.
  //
  // Measured 2026-11-02 (LAC-6527), because the two wirings are NOT equivalent and the
  // difference decides coverage. core.hooksPath REPLACES rather than stacks, so a repo
  // that sets its own defeats the dispatcher; the config hook does not care. zero is
  // git 2.54.0 (Apple Git-157): in a scratch repo with its own core.hooksPath, .../check
  // ran first and the repo's own pre-commit ran after it, so the config arm covers all
  // 26 of 172 repos under zero's $HOME that set a repo-local hooksPath. graphite is
  // 2.50.1 (Apple Git-155), where `git help -c` lists 0 hook.* variables: there the
  // [hook] block below is dead config and a repo with its own hooksPath gets NO identity
  // check at all (LACA-2991, 3 such repos found there). Do not "simplify" this comment
  // into "the config hook does not cover hooksPath repos" -- that is false on zero, and
  // the honest statement is that coverage is a per-host function of the git version.
  //
  // The files themselves are tracked in guard/ and installed by guard/install, which
  // this function runs. Before LAC-6530 they were hand-placed unversioned state in
  // ~/.local/share on each host, and the gate here was existsSync(check && hooks): it
  // preserved wiring it never installed, so a host that had never been hand-seeded was
  // silently rule-18-unguarded. guardWired now means "my own install succeeded", which
  // is why that branch cannot be reached any more on a host that runs setup.
  const guardDir = join(HOME, '.local/share/git-identity-guard');
  const guardCheck = join(guardDir, 'check');
  const guardHooks = join(guardDir, 'hooks');
  const guardInstall = installIdentityGuard(guardDir);
  const guardWired = guardInstall.ok;
  const guard = guardWired
    ? `[hook "identity-guard"]
\tcommand = ${guardCheck}
\tevent = pre-commit
[core]
\thooksPath = ${guardHooks}
`
    : '';

  const content = `# Generated by dotfiles setup — not tracked in git
[user]
\tname = ${name}
\temail = ${email}
${guard}`;

  writeFileSync(localFile, content);
  if (guardWired) {
    p.log.success(
      `Wrote ${pc.dim('~/.gitconfig.local')} (identity guard installed from ${pc.dim('guard/')} and wired, fleet rule 18)`
    );
  } else {
    // Reaching this means guard/install itself failed, which is a real error and not
    // the old "nobody ever hand-seeded this host" case. Say what failed; a host that
    // commits from here has fleet rule 18 unenforced.
    p.log.warn(
      `Wrote ${pc.dim('~/.gitconfig.local')} ${pc.yellow('without an identity guard')}: fleet rule 18 is NOT enforced on this machine.\n` +
        `  ${guardInstall.error}\n` +
        `  Fix that, then run ${pc.dim('guard/verify')} to confirm the guard matches this repo.`
    );
  }

  return { name, email };
}

// Install fleet rule 18's identity guard from guard/ into ~/.local/share. The copy,
// chmod and symlink regeneration live in guard/install rather than here so a host can
// repair the guard without running the whole interactive wizard, and so guard/verify
// has one owner to point at. Returns the rc as a boolean plus the installer's own
// message, which is the only useful thing to print on failure.
function installIdentityGuard(guardDir) {
  const installer = join(DOTFILES_DIR, 'guard', 'install');
  if (!existsSync(installer)) {
    return { ok: false, error: `Missing ${installer}; this checkout predates guard/ (LAC-6530).` };
  }
  try {
    // execFileSync, not execSync: no shell, so a $ or a space in the repo path
    // cannot be interpolated or word-split.
    //
    // GUARD_DEST is passed explicitly rather than inherited. The installer honours it
    // for sandbox testing, and an inherited one would install the guard somewhere the
    // block written below does not wire, which is the silent half-install this whole
    // change exists to remove.
    execFileSync(installer, { stdio: 'pipe', env: { ...process.env, GUARD_DEST: guardDir } });
    return { ok: true, error: null };
  } catch (err) {
    const detail = (err.stderr?.toString() || err.stdout?.toString() || err.message || '').trim();
    return { ok: false, error: `guard/install failed: ${detail.split('\n').pop()}` };
  }
}

async function setupComputerName() {
  if (!IS_MACOS) return null;

  const currentName = getComputerName();

  const name = await p.text({
    message: 'Computer name',
    placeholder: 'my-mac',
    initialValue: currentName,
    validate(value) {
      if (!value || value.trim().length === 0) return 'Name is required';
    },
  });

  if (p.isCancel(name)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  return { name, isWork: false };
}

async function runSymlinks() {
  // Single source of truth: symlink_dotfiles.sh. It recurses into .config/.ssh
  // and symlinks leaf files, so ~/.ssh stays a real directory (keys never end
  // up inside the repo) — don't reimplement that logic here.
  const script = join(DOTFILES_DIR, 'symlink_dotfiles.sh');
  if (!existsSync(script)) {
    p.log.warn('No symlink_dotfiles.sh found');
    return;
  }

  execSync(`bash "${script}"`, {
    stdio: 'inherit',
    cwd: DOTFILES_DIR,
    env: { ...process.env, DIR: DOTFILES_DIR },
  });
}

async function runBrew(isWork) {
  const brewfile = join(DOTFILES_DIR, isWork ? 'Brewfile.work' : 'Brewfile');
  if (!existsSync(brewfile)) {
    p.log.warn(`No ${brewfile} found`);
    return;
  }

  if (!commandExists('brew')) {
    p.log.warn('Homebrew not available — skipping');
    return;
  }

  execSync(`brew bundle --file="${brewfile}"`, {
    stdio: 'inherit',
    cwd: DOTFILES_DIR,
  });
}

async function runNode() {
  const nodeScript = join(DOTFILES_DIR, 'node.sh');
  if (!existsSync(nodeScript)) {
    p.log.warn('No node.sh found');
    return;
  }

  execSync(`bash "${nodeScript}"`, {
    stdio: 'inherit',
    cwd: DOTFILES_DIR,
  });
}

async function runMacOS(computerName) {
  const macScript = join(DOTFILES_DIR, 'apply-macos-settings.sh');
  if (!existsSync(macScript)) {
    p.log.warn('No apply-macos-settings.sh found');
    return;
  }

  p.log.warn('This will change macOS settings for your user. System-level settings stay off unless DOTFILES_ALLOW_SUDO=true.');

  const confirm = await p.confirm({
    message: 'Continue with macOS settings?',
    initialValue: true,
  });

  if (p.isCancel(confirm) || !confirm) {
    p.log.info('Skipped macOS settings');
    return;
  }

  const env = { ...process.env };
  if (computerName) {
    env.DOTFILES_COMPUTER_NAME = computerName.name;
    env.DOTFILES_WORK_MACHINE = computerName.isWork ? 'true' : 'false';
    // Never rename a work machine or change its system settings: IT tracks it by name.
    if (computerName.isWork) env.DOTFILES_ALLOW_SUDO = 'false';
  }

  execSync(`bash "${macScript}"`, {
    stdio: 'inherit',
    cwd: DOTFILES_DIR,
    env,
  });
}

async function runNpmLogin() {
  p.log.info('Opening npm login (interactive browser auth)...');

  return new Promise((resolve) => {
    const child = spawn('npm', ['login'], {
      stdio: 'inherit',
      shell: true,
    });

    child.on('close', (code) => {
      if (code === 0) {
        p.log.success('npm login complete');
      } else {
        p.log.warn('npm login exited with errors');
      }
      resolve();
    });

    child.on('error', () => {
      p.log.warn('Could not run npm login');
      resolve();
    });
  });
}

// ============================================================================
// Main
// ============================================================================

async function main() {
  console.clear();
  p.intro(pc.cyan(pc.bold('  Dotfiles Setup  ')));

  const isWork = await askWorkMachine();

  // ── Git Configuration ─────────────────────────────────────────────────
  p.log.step(pc.bold('Git Configuration'));

  const gitConfig = isWork ? await setupWorkGitConfig() : await setupGitConfig();

  // ── Computer Name (macOS only) ────────────────────────────────────────
  let computerName = null;

  if (IS_MACOS && isWork) {
    // Not prompted: a work machine keeps the name IT gave it.
    computerName = { name: getComputerName(), isWork: true };
  } else if (IS_MACOS) {
    p.log.step(pc.bold('Computer Name'));
    computerName = await setupComputerName();
  }

  // ── Module Selection ──────────────────────────────────────────────────
  const moduleOptions = [
    { value: 'symlinks', label: 'Symlink dotfiles to ~/', hint: 'home/ → ~/' },
    { value: 'brew', label: 'Install Homebrew packages', hint: isWork ? 'Brewfile.work' : 'Brewfile' },
    { value: 'node', label: 'Install Node.js via NVM + Bun', hint: 'node.sh' },
  ];

  if (IS_MACOS) {
    moduleOptions.push({
      value: 'macos',
      label: 'Apply macOS system settings',
      hint: 'per-user defaults',
    });
  }

  moduleOptions.push({
    value: 'npm-login',
    label: 'Run npm login',
    hint: 'browser auth',
  });

  const modules = await p.multiselect({
    message: 'What would you like to set up?',
    options: moduleOptions,
    initialValues: ['symlinks', 'brew', 'node'],
    required: false,
  });

  if (p.isCancel(modules)) {
    p.cancel('Setup cancelled');
    process.exit(0);
  }

  // ── Execute Selected Modules ──────────────────────────────────────────

  if (modules.includes('symlinks')) {
    p.log.step('Symlinking dotfiles...');
    try {
      await runSymlinks();
      p.log.success('Dotfiles symlinked');
    } catch (e) {
      p.log.error(`Symlinks failed: ${e.message}`);
    }
  }

  if (modules.includes('brew')) {
    p.log.step('Installing Homebrew packages...');
    try {
      await runBrew(isWork);
      p.log.success('Homebrew packages installed');
    } catch (e) {
      p.log.error(`Brew install failed: ${e.message}`);
    }
  }

  if (modules.includes('node')) {
    p.log.step('Installing Node.js, NVM, and Bun...');
    try {
      await runNode();
      p.log.success('Node.js environment installed');
    } catch (e) {
      p.log.error(`Node install failed: ${e.message}`);
    }
  }

  if (modules.includes('macos') && IS_MACOS) {
    try {
      await runMacOS(computerName);
      p.log.success('macOS settings applied');
    } catch (e) {
      p.log.error(`macOS settings failed: ${e.message}`);
    }
  }

  if (modules.includes('npm-login')) {
    try {
      await runNpmLogin();
    } catch (e) {
      p.log.error(`npm login failed: ${e.message}`);
    }
  }

  // ── Lacy Shell ────────────────────────────────────────────────────────
  p.log.step('Installing Lacy Shell...');
  try {
    execSync('npx -y lacy@latest', { stdio: 'inherit', cwd: DOTFILES_DIR });
    p.log.success('Lacy Shell installed');
  } catch (e) {
    p.log.error(`Lacy Shell install failed: ${e.message}`);
  }

  // ── Restart (macOS) ─────────────────────────────────────────────────
  if (IS_MACOS && modules.includes('macos')) {
    const restart = await p.confirm({
      message: 'Some macOS settings require a restart. Restart now?',
      initialValue: false,
    });

    if (!p.isCancel(restart) && restart) {
      p.outro('Restarting...');
      execSync('sudo shutdown -r now', { stdio: 'inherit' });
      return;
    }
  }

  // ── Done ──────────────────────────────────────────────────────────────
  p.outro(
    `Done! Run ${pc.cyan('source ~/.zshrc')} or restart your terminal.`
  );
}

main().catch((e) => {
  p.log.error(e.message);
  process.exit(1);
});
